/**
 * Parses generic terminal output to extract test results.
 */
const parseTestResults = (logs) => {
  if (!logs) return null;

  const results = {
    passed: 0,
    failed: 0,
    total: 0,
    snapshots: 0,
    snapshotTotal: 0
  };

  // 1. Try Jest Match (Specific)
  const jestTestMatch = logs.match(/Tests:\s+(?:(\d+)\s+failed,\s+)?(?:(\d+)\s+passed,\s+)?(?:(\d+)\s+total)/);
  if (jestTestMatch) {
    results.failed = parseInt(jestTestMatch[1] || '0');
    results.passed = parseInt(jestTestMatch[2] || '0');
    results.total = parseInt(jestTestMatch[3] || '0');

    const snapshotMatch = logs.match(/Snapshots:\s+(?:(\d+)\s+passed,\s+)?(?:(\d+)\s+total)/);
    if (snapshotMatch) {
      results.snapshots = parseInt(snapshotMatch[1] || '0');
      results.snapshotTotal = parseInt(snapshotMatch[2] || '0');
    }
  } else {
    // 2. Try Generic "X passed, Y failed"
    const genericMatch = logs.match(/(\d+)\s+passed.*?(?:(\d+)\s+failed|(\d+)\s+failures)/i);
    if (genericMatch) {
      results.passed = parseInt(genericMatch[1]);
      results.failed = parseInt(genericMatch[2] || genericMatch[3] || '0');
      results.total = results.passed + results.failed;
    } else {
      // 3. Fallback to simple counts
      const passedCount = logs.match(/(\d+)\s+(?:passed|✔)/i);
      const failedCount = logs.match(/(\d+)\s+(?:failed|failures|✖)/i);
      if (passedCount) results.passed = parseInt(passedCount[1]);
      if (failedCount) results.failed = parseInt(failedCount[1]);
      results.total = results.passed + results.failed;
    }
  }

  return results.total > 0 ? results : null;
};

/**
 * Fetches build history for all jobs in Jenkins.
 * Returns array of build objects with normalized format.
 */
const getAllBuildsHistory = async () => {
  try {
    const url = `${await getBaseUrl()}/api/json?tree=jobs[name,builds[number,result,timestamp,duration,url,actions[parameters[name,value]]]]`;
    const response = await axios.get(url, { headers: getAuthHeader() });
    const jobs = response.data.jobs || [];

    const allBuilds = [];

    for (const job of jobs) {
      const builds = job.builds || [];
      for (const build of builds) {
        const paramsAction = (build.actions || []).find(a => a && a.parameters);
        const params = {};
        if (paramsAction) {
          paramsAction.parameters.forEach(p => {
            params[p.name] = p.value;
          });
        }

        const buildObj = {
          id: `jenkins_${job.name}_${build.number}`,
          projectId: job.name,
          buildNumber: build.number,
          status: build.result === 'SUCCESS' ? 'SUCCESS' : build.result === 'FAILURE' ? 'FAILED' : build.result || 'IN_PROGRESS',
          startTime: new Date(build.timestamp),
          endTime: build.duration > 0 ? new Date(build.timestamp + build.duration) : null,
          duration: build.duration,
          url: build.url,
          params: params
        };

        // If it's a test action, try to fetch logs and parse results
        if (params.ACTION === 'test' && build.result) {
          try {
            const logs = await getBuildLogs(job.name, build.number);
            buildObj.testSummary = parseTestResults(logs);
          } catch (e) {
            console.warn(`Failed to parse test logs for ${job.name}#${build.number}`);
          }
        }

        allBuilds.push(buildObj);
      }
    }

    return allBuilds;
  } catch (error) {
    console.error('Failed to fetch Jenkins build history:', error.message);
    return [];
  }
};

