/**
 * Generates XML config for Jenkins job
 */
const generateConfigXml = (gitUrl, projectType, hasTests = false) => {
  // We update the pipeline template generation to include tests if hasTests is true, 
  // although currently templates have test logic built-in via 'npm test' in stage.
  // For now, we rely on the updated templates in pipelineTemplates.js 
  // which will be updated to include 'npm test'.
  const pipelineScript = projectType === 'REACT'
    ? getReactPipeline(gitUrl)
    : getNodePipeline(gitUrl);

  const escapedScript = pipelineScript
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');

  return `<?xml version='1.1' encoding='UTF-8'?>
<flow-definition plugin="workflow-job">
  <description>Auto-generated by CiGenie for ${gitUrl}</description>
  <keepDependencies>false</keepDependencies>
  <properties>
    <hudson.model.ParametersDefinitionProperty>
      <parameterDefinitions>
        <hudson.model.StringParameterDefinition>
          <name>GIT_REPO</name>
          <defaultValue>${gitUrl}</defaultValue>
          <trim>false</trim>
        </hudson.model.StringParameterDefinition>
        <hudson.model.StringParameterDefinition>
          <name>BRANCH</name>
          <defaultValue>main</defaultValue>
          <trim>false</trim>
        </hudson.model.StringParameterDefinition>
        <hudson.model.StringParameterDefinition>
          <name>ACTION</name>
          <defaultValue>deploy</defaultValue>
          <trim>false</trim>
        </hudson.model.StringParameterDefinition>
        <hudson.model.StringParameterDefinition>
          <name>ENV</name>
          <defaultValue>dev</defaultValue>
          <trim>false</trim>
        </hudson.model.StringParameterDefinition>
        <hudson.model.StringParameterDefinition>
          <name>OUTPUT_PATH</name>
          <defaultValue>/var/www/html</defaultValue>
          <trim>false</trim>
        </hudson.model.StringParameterDefinition>
      </parameterDefinitions>
    </hudson.model.ParametersDefinitionProperty>
  </properties>
  <definition class="org.jenkinsci.plugins.workflow.cps.CpsFlowDefinition" plugin="workflow-cps">
    <script>${escapedScript}</script>
    <sandbox>true</sandbox>
  </definition>
  <triggers/>
  <disabled>false</disabled>
</flow-definition>`;
};

/**
 * Creates a job
 */
const createJob = async (jobName, gitUrl, projectType = 'NODE') => {
  try {
    const crumb = await getCrumb();
    const headers = { ...getAuthHeader(), ...crumb, 'Content-Type': 'application/xml' };
    const configXml = generateConfigXml(gitUrl, projectType);
    const actualJobName = jobName.includes('/') ? jobName.split('/').pop() : jobName;
    const url = `${await getBaseUrl()}/createItem?name=${encodeURIComponent(actualJobName)}`;
    await axios.post(url, configXml, { headers });
    return true;
  } catch (error) {
    throw new Error(`Job Creation Failed: ${error.message}`);
  }
};

